list_01 = [1,8,7,2,21,15]

list_01.sort()      # updates the list to [1,2,7,8,15,21]
list_01.reverse()   #  updates the list to [15,21,2,7,8,1]
list_01.append(8)   # adds 8 at the end of the list
list_01.insert(3,8) # This will add 8 at 3 index
list_01.pop(2)      # Will delete element at index 2 and return its value.
list_01.remove(21)  #  Will remove 21 from the list.